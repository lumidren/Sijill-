"""Regenerate docs/LEGAL-REVIEW.md from the catalog and the configured legal defaults.

  python scripts/legal_review.py

Run it after editing catalog/pdpl-catalog.json; a test fails if the document is out of date.
"""
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "backend"))

from app.catalog import load_path, CATALOG_PATH  # noqa: E402
from app.config import Settings  # noqa: E402

# Facts from the project brief that the software relies on. None has a verified citation.
BRIEF_CLAIMS = [
    ("The Executive Regulations were issued as Decree 816/2025 in November 2025.", "README and product copy (context only)"),
    ("The one-year grace period ended on 1 November 2026.", "README (context only)"),
    ("Controllers and processors need licences, usually valid for three years.", "`licence_validity_years` default; requirement A11.01; licensing questionnaire"),
    ("Separate permits exist for cross-border transfers, electronic marketing and surveillance.", "Requirements A10.02, A11.02, A11.03; licensing questionnaire"),
    ("Every controller and processor must appoint a Data Protection Officer.", "Requirements A01.01, A01.02"),
    ("Breaches must be reported to the regulator within 72 hours.", "`breach_regulator_hours` default; breach clock"),
    ("Affected individuals receive a follow-up notice after the regulator notification.", "`breach_individuals_hours` default (placeholder); breach clock"),
    ("Banks and other CBE-supervised entities are out of scope, except money transfer and currency exchange companies.", "Applicability screener"),
    ("The regulator publishes a self-assessment checklist with 11 assessment areas, and controller/processor register templates.", "Catalog structure (11 areas); register export layouts"),
]


def render() -> str:
    cat = load_path(CATALOG_PATH)
    s = Settings()
    unverified = [r for r in cat.requirements if not r.verified]
    lines = [
        "# Legal review checklist",
        "",
        "PDPL-Ready was built without access to the official texts of Law No. 151 of 2020, its Executive Regulations or",
        "the regulator's checklist and templates. Everything below was drafted in plain language from the project brief and",
        "general data-protection practice, and is marked unverified in the product. A lawyer should work through this list.",
        "",
        "This file is generated by `scripts/legal_review.py` from `catalog/pdpl-catalog.json` and the configuration defaults.",
        "",
        "## How to record a review",
        "",
        "For each requirement, either confirm or correct the English and Arabic text, then in `catalog/pdpl-catalog.json` set the",
        "control's `verified` prop to `true` and add a `source` prop citing article, clause or page. An Admin can also upload the",
        "reviewed catalog in the app (`POST /api/catalog/import`); it is schema-validated before it replaces the shipped one.",
        "Verified requirements lose the \"Unverified\" marker in the UI and in reports. Then re-run `python scripts/legal_review.py`.",
        "",
        f"## 1. Catalog requirements ({len(unverified)} of {len(cat.requirements)} unverified)",
        "",
        "| ID | Area | Requirement | Type | Weight | Status |",
        "|----|------|-------------|------|--------|--------|",
    ]
    for r in cat.requirements:
        area = cat.area(r.area_id)
        status = "verified: " + r.source if r.verified else "**unverified**, source needed"
        kind = "technical" if r.technical else "organisational"
        lines.append(f"| `{r.id}` | {area.label} | {r.title.en} | {kind} | {r.weight} | {status} |")
    lines += [
        "",
        "For each one, check: (1) the obligation exists and is stated correctly; (2) the assessment question asks the right",
        "thing; (3) the guidance contains no wrong legal detail; (4) the Arabic text says the same as the English;",
        "(5) the weight (1-5) reflects its importance; (6) for technical requirements, the mapped checks in",
        "`compliance/prowler/pdpl_egypt_aws.json` and `compliance/linux/pdpl_egypt_linux.json` are relevant evidence.",
        "",
        "## 2. Area structure",
        "",
        "The 11 areas below are modelled on the regulator's self-assessment checklist as described in the brief. Their names",
        "and boundaries are our drafting, not the regulator's:",
        "",
    ]
    for a in cat.areas:
        lines.append(f"- **{a.label}** {a.title.en} / {a.title.ar} ({len(a.requirements)} requirements)")
    lines += [
        "",
        "## 3. Durations and deadlines (configuration, not code)",
        "",
        "These defaults live in `backend/app/config.py` and can be changed with environment variables. None is verified.",
        "",
        "| Setting | Default | Used for | Environment variable |",
        "|---------|---------|----------|----------------------|",
        f"| Regulator breach notification | {s.breach_regulator_hours} hours | Breach clock | `PDPL_BREACH_REGULATOR_HOURS` |",
        f"| Notice to affected individuals | {s.breach_individuals_hours} hours (**placeholder, no source**) | Breach clock | `PDPL_BREACH_INDIVIDUALS_HOURS` |",
        f"| Licence validity | {s.licence_validity_years} years | Renewal dates | `PDPL_LICENCE_VALIDITY_YEARS` |",
        f"| Renewal reminder lead time | {s.renewal_reminder_days} days | Reminders (policy choice, not law) | `PDPL_RENEWAL_REMINDER_DAYS` |",
        f"| Evidence staleness | {s.evidence_stale_days} days | Stale flags (policy choice, not law) | `PDPL_EVIDENCE_STALE_DAYS` |",
        "| Linux log retention threshold | 90 days | Collector check `linux_log_retention_configured` (policy choice) | `--min-log-retention-days` |",
        "",
        "## 4. Facts taken from the project brief",
        "",
        "The software relies on these statements from the brief. They need a citation or correction:",
        "",
        "| Statement | Where the product relies on it |",
        "|-----------|--------------------------------|",
    ]
    for claim, where in BRIEF_CLAIMS:
        lines.append(f"| {claim} | {where} |")
    lines += [
        "",
        "## 5. Wording rules the product already follows",
        "",
        "- Licences and permits are described as \"likely required\", never \"required\".",
        "- The score is called a readiness score and is never presented as legal compliance.",
        "- No article numbers, decree clauses, fees or penalties appear anywhere (a test enforces this for the catalog).",
        "- The app footer and every report carry a not-legal-advice notice.",
        "",
        "## 6. Arabic text",
        "",
        "All Arabic (catalog, interface, reports) was drafted in Modern Standard Arabic without a legal translator. A native",
        "legal-language reviewer should check terminology against the official Arabic text of the Law.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    out = REPO / "docs" / "LEGAL-REVIEW.md"
    out.write_text(render(), encoding="utf-8", newline="\n")
    print("wrote", out.relative_to(REPO))
