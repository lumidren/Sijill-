def state(week: int) -> dict[tuple[str, str], str]:
    """Status of every (check, resource) in a given week (1..WEEKS)."""
    failing = set(BASELINE_FAIL)
    for w in range(2, week + 1):
        failing -= set(FIXES.get(w, []))
        failing |= set(BREAKS.get(w, []))
    out = {}
    for check, resources in CHECK_RES.items():
        for r in resources:
            out[(check, r)] = "FAIL" if (check, r) in failing else "PASS"
    for (check, r), first in APPEARS.items():
        if week >= first:
            out[(check, r)] = "PASS"
    return out


def _severity(sev: str) -> tuple[int, str]:
    order = {"informational": 1, "low": 2, "medium": 3, "high": 4, "critical": 5}
    s = (sev or "medium").lower()
    return order.get(s, 0), s.capitalize() if s in order else "Unknown"


